class InvalidDocument(ValueError):
    pass


def parse_xml(data: bytes):
    try:
        parser = etree.XMLParser(resolve_entities=False, no_network=True, load_dtd=False, remove_blank_text=False, huge_tree=False)
        root = etree.fromstring(data, parser)
        if root.getroottree().docinfo.doctype:
            raise InvalidDocument('Документы с DTD не поддерживаются.')
        return root
    except etree.XMLSyntaxError as e:
        raise InvalidDocument('Некорректный XML внутри DOCX.') from e


def serialize(root, original: bytes) -> bytes:
    """Use a conventional declaration without changing quotation in text data."""
    data = etree.tostring(root, encoding='UTF-8', xml_declaration=False)
    if not original.lstrip().startswith(b'<?xml'):
        return data
    declaration = b'<?xml version="1.0" encoding="UTF-8"'
    if b'standalone=' in original[:120]:
        declaration += b' standalone="yes"' if root.getroottree().docinfo.standalone else b' standalone="no"'
    return declaration + b'?>\n' + data


def _new_xml(root) -> bytes:
    return b'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n' + etree.tostring(root, encoding='UTF-8', xml_declaration=False)


def _normalize_declaration(data: bytes) -> bytes:
    """Normalise only an ASCII XML declaration, leaving payload bytes intact."""
    match = re.match(br'^(\xef\xbb\xbf)?<\?xml\s[^?]*\?>', data)
    if match is None:
        return data
    return match.group().replace(b"'", b'"') + data[match.end():]


def _local(tag: str) -> str:
    return tag.rsplit('}', 1)[-1]


def _source_for_rels(name: str) -> str:
    if name == '_rels/.rels':
        return ''
    directory, filename = posixpath.split(name)
    if posixpath.basename(directory) != '_rels' or not filename.endswith('.rels'):
        raise InvalidDocument('Некорректные связи частей DOCX.')
    return posixpath.join(posixpath.dirname(directory), filename[:-5])


def _target_part(source: str, target: str) -> str:
    parsed = urlsplit(target)
    if parsed.scheme or parsed.netloc or '\\' in target:
        raise InvalidDocument('Некорректная внутренняя ссылка DOCX.')
    path = unquote(parsed.path)
    if not path and source:
        return source
    if path.startswith('/'):
        resolved = posixpath.normpath(path.lstrip('/'))
    else:
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
    if resolved.startswith('../') or resolved in ('..', '.'):
        raise InvalidDocument('Внутренняя ссылка DOCX выходит за пределы документа.')
    return resolved


def _rels_for_part(part: str) -> str:
    directory, filename = posixpath.split(part)
    return posixpath.join(directory, '_rels', filename + '.rels')


def _next_rid(root) -> str:
    used = {node.get('Id') for node in root}
    index = 1
    while f'rId{index}' in used:
        index += 1
    return f'rId{index}'


def _ensure_settings(parts, roots, counts) -> tuple[str, set[str]]:
    """Ensure one valid Word settings part and register it in the OPC package."""
    relname = 'word/_rels/document.xml.rels'
    relroot = roots.get(relname)
    dirty = set()
    if relroot is None:
        relroot = etree.Element(f'{{{REL}}}Relationships', nsmap={None: REL})
        roots[relname] = relroot
        parts[relname] = _new_xml(relroot)
        dirty.add(relname)
    if relroot.tag != f'{{{REL}}}Relationships':
        raise InvalidDocument('Некорректные связи частей DOCX.')
    settings_links = [node for node in relroot if node.get('Type') == SETTINGS_TYPE]
    if len(settings_links) > 1:
        raise InvalidDocument('DOCX содержит несколько частей настроек Word.')
    if settings_links:
        link = settings_links[0]
        if link.get('TargetMode') == 'External':
            raise InvalidDocument('Настройки Word должны находиться внутри DOCX.')
        name = _target_part('word/document.xml', link.get('Target', ''))
        if name not in parts:
            raise InvalidDocument('В DOCX отсутствует часть настроек Word.')
    else:
        name = 'word/settings.xml'
        etree.SubElement(relroot, f'{{{REL}}}Relationship',
                         Id=_next_rid(relroot), Type=SETTINGS_TYPE, Target='settings.xml')
        counts['settings_link_added'] += 1
        dirty.add(relname)
    settings = roots.get(name)
    if settings is None and name in parts:
        settings = parse_xml(parts[name])
    if settings is None:
        settings = etree.Element(f'{{{W}}}settings', nsmap={'w': W})
        parts[name] = _new_xml(settings)
        counts['settings_added'] += 1
    if settings.tag != f'{{{W}}}settings':
        raise InvalidDocument('Некорректная часть настроек Word.')
    roots[name] = settings
    types = roots['[Content_Types].xml']
    overrides = [node for node in types if node.get('PartName') == '/' + name]
    if len(overrides) > 1 or any(node.get('ContentType') != SETTINGS_CONTENT_TYPE for node in overrides):
        raise InvalidDocument('Некорректный тип части настроек Word.')
    if not overrides:
        etree.SubElement(types, f'{{{CT}}}Override', PartName='/' + name, ContentType=SETTINGS_CONTENT_TYPE)
        dirty.add('[Content_Types].xml')
    return name, dirty


def _is_on(node) -> bool | None:
    if node is None:
        return None
    return node.get(f'{{{W}}}val', 'true').lower() not in ('false', '0', 'off')


def _hidden_styles(styles):
    """Return effective run visibility using Word toggle-property inheritance."""
    by_id = {} if styles is None else {n.get(f'{{{W}}}styleId'): n for n in styles.findall(f'{{{W}}}style')}
    default_p = default_c = None
    for sid, node in by_id.items():
        if node.get(f'{{{W}}}default') in ('true', '1', 'on'):
            if node.get(f'{{{W}}}type') == 'paragraph': default_p = sid
            if node.get(f'{{{W}}}type') == 'character': default_c = sid
    defaults = None if styles is None else styles.find(f'{{{W}}}docDefaults/{{{W}}}rPrDefault/{{{W}}}rPr')
    base = tuple(bool(_is_on(None if defaults is None else defaults.find(f'{{{W}}}{kind}'))) for kind in ('vanish', 'webHidden'))

    def chain(sid):
        result, seen = [], set()
        while sid in by_id:
            if sid in seen:
                raise InvalidDocument('Циклическое наследование стилей DOCX.')
            seen.add(sid); node = by_id[sid]; result.append(node)
            based = node.find(f'{{{W}}}basedOn')
            sid = None if based is None else based.get(f'{{{W}}}val')
        return reversed(result)

    def effective(run):
        value = list(base)
        p = next(run.iterancestors(f'{{{W}}}p'), None)
        pstyle = None if p is None else p.find(f'{{{W}}}pPr/{{{W}}}pStyle')
        pstyle = default_p if pstyle is None else pstyle.get(f'{{{W}}}val')
        rpr = run.find(f'{{{W}}}rPr')
        cstyle = None if rpr is None else rpr.find(f'{{{W}}}rStyle')
        cstyle = default_c if cstyle is None else cstyle.get(f'{{{W}}}val')
        for sid in (pstyle, cstyle):
            for node in chain(sid):
                rprops = node.find(f'{{{W}}}rPr')
                for i, kind in enumerate(('vanish', 'webHidden')):
                    on = _is_on(None if rprops is None else rprops.find(f'{{{W}}}{kind}'))
                    if i == 0 and on:
                        value[i] = not value[i]
                    elif i == 1 and on is not None:
                        value[i] = on
        for i, kind in enumerate(('vanish', 'webHidden')):
            direct = _is_on(None if rpr is None else rpr.find(f'{{{W}}}{kind}'))
            if direct is not None: value[i] = direct
        return any(value)
    return effective


def _unwrap(node):
    parent = node.getparent()
    if parent is None:
        return
    index = parent.index(node)
    for child in list(node):
        parent.insert(index, child); index += 1
    parent.remove(node)


def _clean_structure(root, hidden, counts: Counter) -> bool:
    changed = False
    # Paragraph-mark deletions and cell revisions need layout-aware merging.
    # Refuse rather than quietly keep a different final version.
    for node in root.iter():
        if not isinstance(node.tag, str):
            continue
        local = _local(node.tag)
        if node.tag in (f'{{{W}}}cellDel', f'{{{W}}}cellIns', f'{{{W}}}cellMerge'):
            raise InvalidDocument('Есть исправления ячеек таблицы. Сначала примите их в Word и отправьте файл снова.')
        if node.tag == f'{{{W}}}del' and node.getparent() is not None and node.getparent().tag == f'{{{W}}}rPr' and node.getparent().getparent() is not None and node.getparent().getparent().tag == f'{{{W}}}pPr':
            raise InvalidDocument('Есть удалённые знаки абзаца. Сначала примите исправления в Word и отправьте файл снова.')
    for node in list(root.iter()):
        if not isinstance(node.tag, str) or node.getparent() is None:
            continue
        namespace = etree.QName(node).namespace
        local = _local(node.tag)
        if namespace == W and local == 'del' and node.getparent().tag == f'{{{W}}}trPr':
            row = node.getparent().getparent()
            if row is not None and row.tag == f'{{{W}}}tr' and row.getparent() is not None:
                row.getparent().remove(row); counts['revisions'] += 1; changed = True
        elif (namespace == W and local in ('del', 'moveFrom')) or (namespace == W14 and local == 'conflictDel'):
            node.getparent().remove(node); counts['revisions'] += 1; changed = True
        elif (namespace == W and local in ('ins', 'moveTo')) or (namespace == W14 and local == 'conflictIns'):
            _unwrap(node); counts['revisions'] += 1; changed = True
        elif (namespace == W and local in REMOVE_MARKERS) or (namespace in (W14, W15) and local == 'docId'):
            node.getparent().remove(node)
            if local in ('commentReference', 'commentRangeStart', 'commentRangeEnd'):
                counts['comment_markers'] += 1
            elif local.endswith('Change'):
                counts['revisions'] += 1
            changed = True
    for run in list(root.iter(f'{{{W}}}r')):
        if run.getparent() is not None and hidden(run):
            run.getparent().remove(run); counts['hidden_runs'] += 1; changed = True
    for node in root.iter():
        if not isinstance(node.tag, str):
            continue
        for attr in list(node.attrib):
            qname = etree.QName(attr)
            if ((qname.namespace == W and qname.localname.startswith('rsid')) or
                (qname.namespace in (W14, W15) and qname.localname in ('paraId', 'textId', 'docId'))):
                del node.attrib[attr]; counts['revision_ids'] += 1; changed = True
        if any(attr in node.attrib for attr in (f'{{{W}}}author', f'{{{W}}}date')):
            raise InvalidDocument('Есть неподдерживаемые данные исправлений. Примите все исправления в Word перед обработкой.')
    return changed


def _strip_generators(root, counts):
    changed = False
    for element in list(root):
        if element.text and GENERATOR.search(element.text):
            root.remove(element); counts['generators'] += 1; changed = True
    return changed


def _source_created(root, now: datetime) -> datetime | None:
    if root is None:
        return None
    value = root.findtext(f'{{{DCTERMS}}}created')
    if not value:
        return None
    try:
        result = datetime.fromisoformat(value.strip().replace('Z', '+00:00'))
        # Unzoned source dates are ambiguous, so do not invent their timezone.
        if result.tzinfo is None:
            return None
        result = result.astimezone(timezone.utc).replace(microsecond=0)
        return result if result <= now else None
    except (ValueError, OverflowError):
        return None


def _set_metadata(parts, roots, authors, deep, counts, editing_minutes, application_name):
    # An estimate for reviewing/editing existing text, not its composition time.
    counts['minutes'] = min(120, max(1, math.ceil(counts['symbols'] / 1000))) if editing_minutes is None else editing_minutes
    counts['minutes_manual'] = int(editing_minutes is not None)
    now = datetime.now(timezone.utc).replace(microsecond=0)
    source_created = _source_created(roots.get('docProps/core.xml'), now)
    created = source_created or now
    counts['created_preserved'] = int(source_created is not None)
    oldcore = roots.get('docProps/core.xml') if not deep else None
    core = etree.Element(f'{{{CORE_NS}}}coreProperties', nsmap={'cp': CORE_NS, 'dc': DC, 'dcterms': DCTERMS, 'xsi': XSI})
    if oldcore is not None:
        core.extend(list(oldcore)); _strip_generators(core, counts)
    for tag in (f'{{{DC}}}creator', f'{{{CORE_NS}}}lastModifiedBy', f'{{{DCTERMS}}}created', f'{{{DCTERMS}}}modified'):
        for el in core.findall(tag): core.remove(el)
    etree.SubElement(core, f'{{{DC}}}creator').text = '; '.join(authors)
    etree.SubElement(core, f'{{{CORE_NS}}}lastModifiedBy').text = authors[-1]
    for tag, value in (('created', created), ('modified', now)):
        el = etree.SubElement(core, f'{{{DCTERMS}}}{tag}')
        el.set(f'{{{XSI}}}type', 'dcterms:W3CDTF')
        el.text = value.isoformat(timespec='seconds').replace('+00:00', 'Z')
    app = roots.get('docProps/app.xml') if not deep else None
    if app is None: app = etree.Element(f'{{{APP}}}Properties', nsmap={None: APP})
    _strip_generators(app, counts)
    for tag in ('TotalTime', 'Application'):
        for el in app.findall(f'{{{APP}}}{tag}'):
            app.remove(el)
    # TotalTime belongs before Company/LinksUpToDate in the ECMA properties order.
    order = ['Template', 'Manager', 'Company', 'Pages', 'Words', 'Characters', 'PresentationFormat', 'Lines', 'Paragraphs', 'Slides', 'Notes', 'TotalTime', 'HiddenSlides', 'MMClips', 'ScaleCrop', 'HeadingPairs', 'TitlesOfParts', 'LinksUpToDate', 'CharactersWithSpaces', 'SharedDoc', 'HyperlinkBase', 'HLinks', 'HyperlinksChanged', 'DigSig', 'Application', 'AppVersion', 'DocSecurity']
    total = etree.Element(f'{{{APP}}}TotalTime'); total.text = str(counts['minutes'])
    insert_at = next((i for i, el in enumerate(app) if _local(el.tag) in order and order.index(_local(el.tag)) > order.index('TotalTime')), len(app))
    app.insert(insert_at, total)
    application = etree.Element(f'{{{APP}}}Application')
    application.text = application_name
    insert_at = next((i for i, el in enumerate(app) if _local(el.tag) in order and order.index(_local(el.tag)) > order.index('Application')), len(app))
    app.insert(insert_at, application)
    for name, root in (('docProps/core.xml', core), ('docProps/app.xml', app)):
        parts[name] = _new_xml(root)
    relroot = roots['_rels/.rels']
    used = {el.get('Id') for el in relroot}
    for kind, target in ((CORE_TYPE, 'docProps/core.xml'), (APP_TYPE, 'docProps/app.xml')):
        i = 1
        while f'rId{i}' in used: i += 1
        rid = f'rId{i}'; used.add(rid)
        etree.SubElement(relroot, f'{{{REL}}}Relationship', Id=rid, Type=kind, Target=target)
    ctr = roots['[Content_Types].xml']
    etree.SubElement(ctr, f'{{{CT}}}Override', PartName='/docProps/core.xml', ContentType='application/vnd.openxmlformats-package.core-properties+xml')
    etree.SubElement(ctr, f'{{{CT}}}Override', PartName='/docProps/app.xml', ContentType='application/vnd.openxmlformats-officedocument.extended-properties+xml')


def clean_docx(content: bytes, deep: bool = True, authors: list[str] | None = None,
               *, editing_minutes: int | None = None,
               application_name: str = DEFAULT_APPLICATION) -> tuple[bytes, Counter]:
    if len(content) > MAX_INPUT:
        raise InvalidDocument('Файл больше 20 МБ.')
    if editing_minutes is not None and (
            isinstance(editing_minutes, bool) or not isinstance(editing_minutes, int)
            or not 0 <= editing_minutes <= MAX_EDITING_MINUTES):
        raise InvalidDocument('Время редактирования должно быть целым числом от 0 до 10080 минут.')
    if (not isinstance(application_name, str) or not application_name.strip()
            or len(application_name.strip()) > 100 or any(ord(ch) < 32 for ch in application_name)):
        raise InvalidDocument('Название приложения должно содержать от 1 до 100 символов.')
    application_name = application_name.strip()
    try:
        etree.Element('test').text = application_name
    except ValueError as e:
        raise InvalidDocument('В названии приложения есть недопустимые символы.') from e
    if authors is not None:
        if not authors or any(not isinstance(a, str) or not a.strip() for a in authors):
            raise InvalidDocument('Укажите хотя бы одного автора.')
        authors = [a.strip() for a in authors]
        if len('; '.join(authors)) > 200:
            raise InvalidDocument('Имена авторов слишком длинные: максимум 200 символов.')
        try:
            etree.Element('test').text = '; '.join(authors)
        except ValueError as e:
            raise InvalidDocument('В именах авторов есть недопустимые символы.') from e
    counts = Counter()
    try:
        with ZipFile(BytesIO(content)) as zin:
            infos = zin.infolist(); names = [i.filename for i in infos]
            if (len(infos) > MAX_ENTRIES or sum(i.file_size for i in infos) > MAX_UNPACKED or len(names) != len(set(names)) or any(i.flag_bits & 1 for i in infos)):
                raise InvalidDocument('Архив слишком большой, зашифрован или содержит повторяющиеся файлы.')
            if any(n.startswith('/') or '\\' in n or any(p in ('.', '..') for p in n.split('/')) for n in names):
                raise InvalidDocument('Некорректные имена частей DOCX.')
            if not {'[Content_Types].xml', 'word/document.xml', '_rels/.rels'}.issubset(names):
                raise InvalidDocument('Это не поддерживаемый DOCX.')
            if any(n.lower().endswith('vbaproject.bin') for n in names):
                raise InvalidDocument('Документы с макросами не поддерживаются.')
            parts = {i.filename: zin.read(i) for i in infos if not i.is_dir()}
        roots = {name: parse_xml(data) for name, data in parts.items() if name.endswith('.rels') or name == '[Content_Types].xml' or (name.startswith(('word/', 'docProps/')) and name.endswith('.xml'))}
        if roots['word/document.xml'].tag != f'{{{W}}}document':
            raise InvalidDocument('Поддерживается обычный Word DOCX (Transitional). Формат Strict и нестандартные документы не поддерживаются.')
        if roots['_rels/.rels'].tag != f'{{{REL}}}Relationships' or roots['[Content_Types].xml'].tag != f'{{{CT}}}Types':
            raise InvalidDocument('Некорректная структура DOCX.')
        mainlinks = [el for el in roots['_rels/.rels'] if el.get('Type', '').endswith('/officeDocument')]
        if len(mainlinks) != 1 or mainlinks[0].get('TargetMode') == 'External' or _target_part('', mainlinks[0].get('Target', '')) != 'word/document.xml':
            raise InvalidDocument('Некорректная связь основного документа DOCX.')
        ctypes = roots['[Content_Types].xml']
        if any('macroenabled' in el.get('ContentType', '').lower() for el in ctypes):
            raise InvalidDocument('Документы с макросами не поддерживаются.')
        main_types = [el.get('ContentType') for el in ctypes if el.get('PartName') == '/word/document.xml']
        if main_types != ['application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml']:
            raise InvalidDocument('Основная часть файла не является обычным документом DOCX.')
        if deep and (any(n.lower().startswith('_xmlsignatures/') for n in names) or any('digital-signature' in el.get('ContentType', '') for el in ctypes)):
            raise InvalidDocument('Документ подписан цифровой подписью. Обработка изменит файл и нарушит подпись; используйте неподписанную копию.')
        if deep and (any(n.lower().startswith(('word/embeddings/', 'word/activex/')) for n in names) or any(any(token in el.get('ContentType', '').lower() for token in ('oleobject', 'activex')) for el in ctypes)):
            raise InvalidDocument('Есть встроенные файлы или ActiveX. Удалите их из копии в Word перед расширенной обработкой.')
        settings_part, settings_dirty = _ensure_settings(parts, roots, counts)
        removed = set()
        if deep:
            removed |= DOC_PROPS.intersection(parts)
            for name in parts:
                base = posixpath.basename(name).lower()
                if (name.lower().startswith('customxml/') or
                    (name.startswith('word/') and (base.startswith('comments') or base == 'people.xml' or '/printerSettings/' in name)) or
                    (name.startswith('docProps/') and base.startswith('thumbnail.'))):
                    removed.add(name)
            for relname, root in roots.items():
                if not relname.endswith('.rels'): continue
                source = _source_for_rels(relname)
                for el in root:
                    ending = el.get('Type', '').rsplit('/', 1)[-1]
                    if ending in REMOVE_REL_ENDINGS and el.get('TargetMode') != 'External' and el.get('Target'):
                        removed.add(_target_part(source, el.get('Target')))
            # The settings relationship is authoritative even when its valid
            # custom filename happens to resemble a comment/custom-XML part.
            removed.discard(settings_part)
            for name in removed.copy(): removed.add(_rels_for_part(name))
            counts['comments'] = sum(len(root.findall(f'{{{W}}}comment')) for name, root in roots.items() if name in removed)
            counts['custom_xml_parts'] = sum(n.lower().startswith('customxml/') and not n.endswith('.rels') for n in removed if n in parts)
            counts['properties'] = len(DOC_PROPS.intersection(parts))
        if authors is not None:
            removed |= {'docProps/core.xml', 'docProps/app.xml'}.intersection(parts)
        hidden = _hidden_styles(roots.get('word/styles.xml'))
        dirty = {'_rels/.rels', '[Content_Types].xml'} | settings_dirty
        for name, root in roots.items():
            if name in removed: continue
            if name.endswith('.rels'):
                if root.tag != f'{{{REL}}}Relationships':
                    raise InvalidDocument('Некорректные связи частей DOCX.')
                source = _source_for_rels(name)
                ids = set()
                for el in list(root):
                    rid = el.get('Id')
                    if not rid or rid in ids: raise InvalidDocument('Повторяющиеся или пустые идентификаторы связей DOCX.')
                    ids.add(rid)
                    target = el.get('Target', '')
                    endpoint = el.get('Type', '').rsplit('/', 1)[-1]
                    remove = ((deep and endpoint in REMOVE_REL_ENDINGS) or (name == '_rels/.rels' and el.get('Type') in (PROP_TYPES if deep else ({CORE_TYPE, APP_TYPE} if authors is not None else set()))))
                    if el.get('TargetMode') != 'External':
                        targetpart = _target_part(source, target)
                        remove = remove or targetpart in removed
                        if not remove and targetpart not in parts:
                            raise InvalidDocument('В DOCX отсутствует часть, на которую ссылается документ.')
                    if remove:
                        root.remove(el); dirty.add(name)
                    elif el.get('TargetMode') == 'External':
                        counts['external_links'] += 1
                        cleaned = strip_utm(target)
                        if cleaned != target:
                            el.set('Target', cleaned); dirty.add(name); counts['links'] += 1
            elif (name.startswith('word/') and name.endswith('.xml')) or name == settings_part:
                if deep and _clean_structure(root, hidden, counts): dirty.add(name)
                if clean_word_text(root, deep, counts): dirty.add(name)
            elif name in DOC_PROPS and not deep:
                if _strip_generators(root, counts): dirty.add(name)
        if deep:
            # A deleted/hidden run can leave its image or hyperlink relationship
            # behind. Remove only relationship kinds that are explicitly referenced
            # in the owning XML; styles/settings and other implicit kinds stay.
            rel_ns = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
            office_ns = 'urn:schemas-microsoft-com:office:office'
            for name, relroot in roots.items():
                if not name.endswith('.rels') or name in removed:
                    continue
                source = _source_for_rels(name)
                owner = roots.get(source)
                if owner is None or source in removed:
                    continue
                referenced = set()
                for node in owner.iter():
                    for key, value in node.attrib.items():
                        qname = etree.QName(key)
                        if qname.namespace == rel_ns or (qname.namespace == office_ns and qname.localname == 'relid'):
                            referenced.update(value.split())
                for rel in list(relroot):
                    if rel.get('Type', '').rsplit('/', 1)[-1] in ('image', 'hyperlink') and rel.get('Id') not in referenced:
                        relroot.remove(rel); dirty.add(name); counts['unused_relationships'] += 1
        counts['symbols'] = sum(len(el.text or '') for el in roots['word/document.xml'].iter(f'{{{W}}}t'))
        counts['fields'] = sum(1 for name, root in roots.items() if name.startswith('word/') and name not in removed for el in root.iter() if el.tag in (f'{{{W}}}instrText', f'{{{W}}}fldSimple'))
        if deep:
            # Drop orphan package parts as they may be old comment media or stale data.
            reachable, pending = set(), ['']
            while pending:
                source = pending.pop()
                relname = '_rels/.rels' if not source else _rels_for_part(source)
                if relname in roots and relname not in removed:
                    reachable.add(relname)
                    for rel in roots[relname]:
                        if rel.get('TargetMode') == 'External': continue
                        target = _target_part(source, rel.get('Target', ''))
                        if target not in reachable and target not in removed:
                            reachable.add(target); pending.append(target)
            removed |= set(parts) - reachable - {'[Content_Types].xml'}
        for el in list(ctypes):
            if el.get('PartName', '').lstrip('/') in removed:
                ctypes.remove(el)
        for name in removed:
            parts.pop(name, None)
        counts['removed_parts'] = sum(n in names for n in removed)
        counts['media_files'] = sum(n.startswith('word/media/') for n in parts)
        if authors is not None:
            _set_metadata(parts, roots, authors, deep, counts, editing_minutes, application_name)
        for name in dirty:
            if name in parts: parts[name] = serialize(roots[name], parts[name])
        # Metadata is synthesized separately; do not overwrite it from old roots.
        output = BytesIO()
        with ZipFile(output, 'w', compression=ZIP_DEFLATED) as zout:
            for name, data in parts.items():
                entry = ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0)); entry.compress_type = ZIP_DEFLATED
                if name.endswith(('.xml', '.rels')):
                    data = _normalize_declaration(data)
                zout.writestr(entry, data)
        return output.getvalue(), counts
    except (BadZipFile, RuntimeError, OSError, KeyError, NotImplementedError) as e:
        raise InvalidDocument('Не удалось прочитать DOCX. Проверьте, что файл не повреждён и не защищён паролем.') from e
